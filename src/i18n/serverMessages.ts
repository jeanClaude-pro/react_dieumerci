export function serverMessage(message: string | null | undefined, fallback = ""): string {
  const text = String(message ?? "").trim();
  if (!text) return fallback;
  const key = EXACT[text];
  if (key) return i18n.t(`server.${key}`);
  for (const [pattern, name] of PATTERNS) {
    const match = pattern.exec(text);
    if (match) return i18n.t(`server.p.${name}`, { ...(match.groups ?? {}) });
  }
  return text;
}
